param([Parameter(Mandatory)][string]$FixtureDirectory,
    [ValidateSet('dashboard','appearance')][string]$Check = 'dashboard',
    [string[]]$Pages = @('admin','teacher','school','parent'))
$ErrorActionPreference = 'Stop'
$resolved = (Resolve-Path -LiteralPath $FixtureDirectory).Path
$allowedRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../storage/local-preview'))
if (!$resolved.StartsWith($allowedRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase) -or (Split-Path $resolved -Leaf) -notmatch '^dashboard-ui-[a-f0-9]{12}$') { throw 'Use only the synthetic fixture directory generated by the dashboard HTTP suite.' }
foreach ($fixtureName in $Pages) {
    if ($fixtureName -notmatch '^[a-z-]+$' -or !(Test-Path -LiteralPath (Join-Path $resolved ($fixtureName + '.html')))) { throw 'Generate the requested synthetic HTML fixtures first.' }
}
$previewRoot = Join-Path $resolved 'screenshots'
New-Item -ItemType Directory -Path $previewRoot -Force | Out-Null
$profilePath = Join-Path $previewRoot ('isolated-browser-' + [guid]::NewGuid().ToString('N'))
$browserProcess = Start-Process -FilePath 'C:/Program Files/Google/Chrome/Application/chrome.exe' -ArgumentList @('--headless=new','--disable-gpu','--no-first-run','--no-default-browser-check',('--user-data-dir=' + $profilePath),'--remote-debugging-port=0','about:blank') -WindowStyle Hidden -PassThru
$socket = [Net.WebSockets.ClientWebSocket]::new()
$script:previewSequence = 0
function Invoke-PreviewProtocol([string]$method, [hashtable]$parameters) {
    $script:previewSequence++
    $message = @{id=$script:previewSequence;method=$method;params=$parameters} | ConvertTo-Json -Depth 15 -Compress
    $payload = [Text.Encoding]::UTF8.GetBytes($message)
    $deadline = [Threading.CancellationTokenSource]::new(20000)
    try {
        $socket.SendAsync([ArraySegment[byte]]::new($payload),[Net.WebSockets.WebSocketMessageType]::Text,$true,$deadline.Token).GetAwaiter().GetResult() | Out-Null
        do {
            $stream = [IO.MemoryStream]::new()
            try {
                do {
                    $buffer = [byte[]]::new(65536)
                    $received = $socket.ReceiveAsync([ArraySegment[byte]]::new($buffer),$deadline.Token).GetAwaiter().GetResult()
                    $stream.Write($buffer,0,$received.Count)
                    if ($stream.Length -gt 16777216) { throw 'Preview response exceeded its bound.' }
                } until ($received.EndOfMessage)
                $response = [Text.Encoding]::UTF8.GetString($stream.ToArray()) | ConvertFrom-Json -AsHashtable
            } finally { $stream.Dispose() }
        } until ($response.id -eq $script:previewSequence)
        if ($response.ContainsKey('error')) { throw ('Preview command failed: ' + $method) }
        return $response.result
    } finally { $deadline.Dispose() }
}
try {
    $end = [DateTime]::UtcNow.AddSeconds(20)
    $portFile = Join-Path $profilePath 'DevToolsActivePort'
    while (!(Test-Path -LiteralPath $portFile) -and [DateTime]::UtcNow -lt $end) { Start-Sleep -Milliseconds 100 }
    $port = [int](Get-Content -LiteralPath $portFile -First 1)
    $targets = Invoke-RestMethod -Uri ('http://127.0.0.1:' + $port + '/json/list')
    $target = @($targets | Where-Object { $_.type -eq 'page' })[0]
    $socket.ConnectAsync([Uri]$target.webSocketDebuggerUrl,[Threading.CancellationToken]::None).GetAwaiter().GetResult() | Out-Null
    Invoke-PreviewProtocol 'Network.enable' @{} | Out-Null
    Invoke-PreviewProtocol 'Network.setBlockedURLs' @{urls=@('*fonts.googleapis.com*','*fonts.gstatic.com*')} | Out-Null
    $checkScript = if ($Check -eq 'appearance') { 'tests/appearance-browser.js' } else { 'tests/dashboard-ui-browser.js' }
    $checkSource = [IO.File]::ReadAllText((Join-Path $PWD $checkScript))
    foreach ($role in $Pages) {
        if ($role -notmatch '^[a-z-]+$') { throw 'Invalid synthetic fixture name.' }
        foreach ($width in @(360,768,1440)) {
            Invoke-PreviewProtocol 'Emulation.setDeviceMetricsOverride' @{width=$width;height=1000;deviceScaleFactor=1;mobile=$true} | Out-Null
            $url = 'file:///' + (Join-Path $resolved ($role + '.html')).Replace('\','/')
            Invoke-PreviewProtocol 'Page.navigate' @{url=$url} | Out-Null
            Invoke-PreviewProtocol 'Runtime.evaluate' @{expression='new Promise(resolve=>{let ticks=0;const timer=setInterval(()=>{if((document.readyState==="complete"&&document.documentElement.hasAttribute("data-theme-preference"))||++ticks>150){clearInterval(timer);resolve()}},100)})';awaitPromise=$true;returnByValue=$true} | Out-Null
            $result = Invoke-PreviewProtocol 'Runtime.evaluate' @{expression=$checkSource;awaitPromise=$true;returnByValue=$true}
            if ($result.ContainsKey('exceptionDetails')) {
                $diagnostic = Invoke-PreviewProtocol 'Runtime.evaluate' @{expression='JSON.stringify({url:location.href,ready:document.readyState,workspace:document.querySelector("[data-dashboard-workspace]")?.className,body:document.body?.innerText.slice(0,180),scripts:[...document.scripts].map(x=>x.src)})';returnByValue=$true}
                Write-Output $diagnostic.result.value
                throw ($role + ' ' + $width + ': ' + ($result.exceptionDetails | ConvertTo-Json -Depth 8 -Compress)) }
            Write-Output ($role + ': ' + $result.result.value)
            $shot = Invoke-PreviewProtocol 'Page.captureScreenshot' @{format='png';captureBeyondViewport=$false}
            [IO.File]::WriteAllBytes((Join-Path $previewRoot ($role + '-' + $width + '.png')),[Convert]::FromBase64String($shot.data))
            if ($width -eq 360 -and $Check -eq 'dashboard') {
                Invoke-PreviewProtocol 'Runtime.evaluate' @{expression='document.querySelector("[data-dashboard-menu]").click()';returnByValue=$true} | Out-Null
                foreach ($resize in @(1440,360,1440,360)) {
                    Invoke-PreviewProtocol 'Emulation.setDeviceMetricsOverride' @{width=$resize;height=1000;deviceScaleFactor=1;mobile=$true} | Out-Null
                    $focus = Invoke-PreviewProtocol 'Runtime.evaluate' @{expression='new Promise(resolve=>setTimeout(()=>resolve(JSON.stringify({visible:!!document.activeElement.getClientRects().length,inert:document.querySelector(".dashboard-body").inert,open:document.querySelector("[data-dashboard-workspace]").classList.contains("dashboard-menu-open")})),100))';awaitPromise=$true;returnByValue=$true}
                    $state = $focus.result.value | ConvertFrom-Json
                    if (!$state.visible -or $state.inert -or $state.open) { throw ($role + ': focus/background failed during breakpoint change') }
                }
                Write-Output ($role + ': PASS open-menu and closed-Menu breakpoint focus recovery')
            }
        }
    }
    try { Invoke-PreviewProtocol 'Browser.close' @{} | Out-Null } catch { }
} finally {
    $socket.Dispose()
    if (!$browserProcess.HasExited) { Stop-Process -Id $browserProcess.Id -ErrorAction SilentlyContinue }
}
