param([Parameter(Mandatory)][string]$FixtureDirectory)
$ErrorActionPreference = 'Stop'
$source = (Resolve-Path -LiteralPath $FixtureDirectory).Path
$allowedRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../storage/local-preview'))
if (!$source.StartsWith($allowedRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase) -or (Split-Path $source -Leaf) -notmatch '^settings-[a-f0-9]{12}$') { throw 'Use only the synthetic fixture directory generated by tests/settings.php.' }
$destination = Join-Path $allowedRoot ('dashboard-ui-' + [guid]::NewGuid().ToString('N').Substring(0,12))
New-Item -ItemType Directory -Path $destination | Out-Null
foreach ($role in @('teacher','school','parent','admin')) {
    Copy-Item -LiteralPath (Join-Path $source ($role + '-settings-preview.html')) -Destination (Join-Path $destination ($role + '.html'))
}
foreach ($page in @('home','login','register','library','messages')) {
    Copy-Item -LiteralPath (Join-Path $source ($page + '-preview.html')) -Destination (Join-Path $destination ($page + '.html'))
}
Write-Output ('Synthetic browser fixtures: ' + $destination)
& (Join-Path $PSScriptRoot 'dashboard-ui-browser.ps1') -FixtureDirectory $destination
& (Join-Path $PSScriptRoot 'dashboard-ui-browser.ps1') -FixtureDirectory $destination -Check appearance -Pages @('home','login','register','library','messages')
